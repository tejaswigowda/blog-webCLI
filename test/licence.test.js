// R3: the repository is licensed per surface, and the script that lands in other people's pages is built only from the runtime.
import test from 'node:test';
import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { TARGETS, bundleInputs } from '../cli/build-live.js';
import { LIVE_SOURCE } from '../lib/live-source.js';
import { SEARCH_SOURCE } from '../lib/search-source.js';
import { buildSite } from '../lib/blog.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => fs.readFile(path.join(root, f), 'utf8');

// The runtime: what generated pages carry. Each directory has its own permissive LICENSE.
const RUNTIME = [
  { dir: 'lib/', licence: /^MIT License\b/ },
  { dir: 'vendor/moment/', licence: /Permission is hereby granted, free of charge/ },
];

test('R3: a generated page\'s scripts are built only from the runtime directories', async () => {
  for (const t of TARGETS) {
    const inputs = await bundleInputs(t);
    assert.ok(inputs.length > 1, `${t.name} has inputs`);
    for (const f of inputs) assert.ok(RUNTIME.some((r) => f.startsWith(r.dir)), `${t.out} is built from ${f}, which is outside the runtime (${RUNTIME.map((r) => r.dir).join(', ')})`);
    for (const tool of ['app/', 'cli/', 'blog/', 'vendor/quill/', 'index.html']) assert.ok(!inputs.some((f) => f.startsWith(tool)), `${t.out} contains ${tool}`);
  }
});

test('R3: each runtime directory carries its own permissive licence', async () => {
  for (const r of RUNTIME) assert.match(await read(`${r.dir}LICENSE`), r.licence, `${r.dir}LICENSE`);
  assert.match(await read('lib/LICENSE'), /MIT License[\s\S]*Permission is hereby granted/);
  assert.ok(!/GNU GENERAL PUBLIC|GPL/.test(await read('lib/LICENSE')));
});

test('R3: the top-level licence states both surfaces and which applies where; the GPL text is kept whole', async () => {
  const top = await read('LICENSE');
  for (const need of ['RUNTIME', 'lib/', 'MIT', 'TOOL', 'app/', 'cli/', 'GPL-3.0-only', 'LICENSE-GPL-3.0', 'licences-inventory.json']) assert.ok(top.includes(need), `LICENSE says ${need}`);
  assert.match(await read('LICENSE-GPL-3.0'), /GNU GENERAL PUBLIC LICENSE\s+Version 3, 29 June 2007/);
  const pkg = JSON.parse(await read('package.json'));
  assert.equal(pkg.license, 'SEE LICENSE IN LICENSE', 'a bare SPDX string cannot say two things');
});

test('R3: the shipped scripts and the pages carry the runtime\'s licence, and the notice moment.js asks for', async () => {
  assert.match(LIVE_SOURCE, /^\/\*[^*]*MIT \(c\) 2026 Tejaswi Gowda and blog-webCLI contributors/, 'the live script says whose it is');
  assert.match(LIVE_SOURCE.slice(0, 600), /Includes moment\.js, MIT \(c\) JS Foundation and other contributors/);
  assert.match(SEARCH_SOURCE.slice(0, 400), /MIT \(c\) 2026/);
  assert.ok(!/GPL/.test(LIVE_SOURCE.slice(0, 600)), 'no GPL claim in the banner');
  const r = buildSite({ blog: { title: 'T', description: 'D', author: 'A', domain: 'https://example.test', repo: 'me/blog' }, posts: [{ path: 'posts/a.md', text: '---\nslug: a\ntitle: A\ndate: 2026-01-01\nstatus: published\n---\n\nhi\n' }], lock: {} });
  assert.match(r.files['index.html'], /Generated by blog-webcli \(MIT\)\. Licences this page depends on:\s+theme: default — MIT — built in/);
  assert.equal(JSON.parse(r.files['licences.json']).generator.licence, 'MIT');
});
