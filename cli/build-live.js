// Builds lib/live-source.js: the text of webcli-live.js, the one script generated pages load.
//   node cli/build-live.js          write it
//   node cli/build-live.js --check  fail if lib/live-source.js is not what the sources build to
// It is committed, not built at publish, because the generator is pure and runs in a browser: it can only
// hand a page a string it already has. A test runs --check, so the script a blog ships is never stale.
import { build } from 'esbuild';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { VERSION } from '../lib/version.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(root, 'lib', 'live-source.js');

// lib/blog.js imports the finished script to write it out; the script itself must not contain itself.
const withoutSelf = {
  name: 'without-live-source',
  setup(b) {
    b.onResolve({ filter: /live-source\.js$/ }, () => ({ path: 'live-source', namespace: 'stub' }));
    b.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({ contents: "export const LIVE_SOURCE = '';", loader: 'js' }));
  },
};

export async function buildLive() {
  const result = await build({
    entryPoints: [path.join(root, 'lib', 'live-entry.js')],
    bundle: true,
    write: false,
    format: 'esm',
    target: 'es2020',
    minify: true,
    legalComments: 'none',
    plugins: [withoutSelf],
    banner: { js: `/* blog-webcli ${VERSION} live renderer (GPL-3.0-only). Source: lib/live-entry.js in blog.webcli.app. */` },
  });
  const code = result.outputFiles[0].text;
  return `// Generated by cli/build-live.js from lib/live-entry.js. Do not edit.\nexport const LIVE_SOURCE = ${JSON.stringify(code)};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = await buildLive();
  if (process.argv.includes('--check')) {
    const have = await fs.readFile(OUT, 'utf8').catch(() => '');
    if (have !== text) {
      console.error('lib/live-source.js is stale: run `node cli/build-live.js`');
      process.exit(1);
    }
    console.log('ok: lib/live-source.js matches its sources');
  } else {
    await fs.writeFile(OUT, text);
    console.log(`wrote lib/live-source.js (${text.length} bytes)`);
  }
}
