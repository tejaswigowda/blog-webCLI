// Builds the two scripts generated pages can load, as strings the pure generator can hand out:
//   lib/live-source.js    webcli-live.js    (from lib/live-entry.js)    the freshness check and 404 renderer
//   lib/search-source.js  webcli-search.js  (from lib/search-entry.js)  the search page
//   node cli/build-live.js          write them
//   node cli/build-live.js --check  fail if either is not what the sources build to
// They are committed, not built at publish, because the generator is pure and runs in a browser: it can only
// hand a page a string it already has. A test runs --check, so the script a blog ships is never stale.
import { build } from 'esbuild';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { VERSION } from '../lib/version.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

// lib/blog.js imports the finished scripts to write them out; a script itself must not contain them.
const withoutSelf = {
  name: 'without-built-sources',
  setup(b) {
    b.onResolve({ filter: /(live|search)-source\.js$/ }, (a) => ({ path: path.basename(a.path), namespace: 'stub' }));
    b.onLoad({ filter: /.*/, namespace: 'stub' }, (a) => ({ contents: `export const ${a.path.startsWith('live') ? 'LIVE_SOURCE' : 'SEARCH_SOURCE'} = '';`, loader: 'js' }));
  },
};

export const TARGETS = [
  { name: 'live', entry: 'live-entry.js', out: 'live-source.js', constant: 'LIVE_SOURCE', what: 'live renderer' },
  { name: 'search', entry: 'search-entry.js', out: 'search-source.js', constant: 'SEARCH_SOURCE', what: 'search page' },
];

export async function buildTarget(t) {
  const result = await build({
    entryPoints: [path.join(root, 'lib', t.entry)],
    bundle: true,
    write: false,
    format: 'esm',
    target: 'es2020',
    minify: true,
    legalComments: 'none',
    plugins: [withoutSelf],
    banner: { js: `/* blog-webcli ${VERSION} ${t.what} (GPL-3.0-only). Source: lib/${t.entry} in blog.webcli.app. */` },
  });
  const code = result.outputFiles[0].text;
  return `// Generated by cli/build-live.js from lib/${t.entry}. Do not edit.\nexport const ${t.constant} = ${JSON.stringify(code)};\n`;
}

// Kept for the existing drift test.
export const buildLive = () => buildTarget(TARGETS[0]);

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = false;
  for (const t of TARGETS) {
    const text = await buildTarget(t);
    const file = path.join(root, 'lib', t.out);
    if (check) {
      const have = await fs.readFile(file, 'utf8').catch(() => '');
      if (have !== text) {
        console.error(`lib/${t.out} is stale: run \`node cli/build-live.js\``);
        stale = true;
      } else console.log(`ok: lib/${t.out} matches its sources`);
    } else {
      await fs.writeFile(file, text);
      console.log(`wrote lib/${t.out} (${text.length} bytes)`);
    }
  }
  if (stale) process.exit(1);
}
