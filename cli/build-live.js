// Builds the scripts generated pages can load, as strings the pure generator can hand out:
//   lib/live-source.js    webcli-live.js    (from lib/live-entry.js)    the freshness check and 404 renderer
//   lib/search-source.js  webcli-search.js  (from lib/search-entry.js)  the search page
//   lib/slideshow-source.js  webcli-slideshow.js  (from lib/slideshow-entry.js)  slideshow controls
//   lib/math-source.js  webcli-math.js  (from lib/math-entry.js)  lazy live math, never initial page rendering
//   node cli/build-live.js          write them
//   node cli/build-live.js --check  fail if any is not what the sources build to
// They are committed, not built at publish, because the generator is pure and runs in a browser: it can only
// hand a page a string it already has. A test runs --check, so the script a blog ships is never stale.
import { build } from 'esbuild';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { VERSION } from '../lib/version.js';
import { parse } from 'acorn';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

// lib/blog.js imports the finished scripts to write them out; a script itself must not contain them.
const withoutSelf = {
  name: 'without-built-sources',
  setup(b) {
    b.onResolve({ filter: /(live|search|slideshow|math)-source\.js$/ }, (a) => ({ path: path.basename(a.path), namespace: 'stub' }));
    b.onLoad({ filter: /.*/, namespace: 'stub' }, (a) => ({ contents: `export const ${a.path.split('-')[0].toUpperCase()}_SOURCE = '';`, loader: 'js' }));
  },
};

export const TARGETS = [
  { name: 'live', entry: 'live-entry.js', out: 'live-source.js', constant: 'LIVE_SOURCE', what: 'live renderer' },
  { name: 'search', entry: 'search-entry.js', out: 'search-source.js', constant: 'SEARCH_SOURCE', what: 'search page' },
  { name: 'slideshow', entry: 'slideshow-entry.js', out: 'slideshow-source.js', constant: 'SLIDESHOW_SOURCE', what: 'slideshow controls' },
  { name: 'math', entry: 'math-entry.js', out: 'math-source.js', constant: 'MATH_SOURCE', what: 'live math renderer' },
];

async function bundle(t) {
  const notices = [`MIT (c) 2026 Tejaswi Gowda and blog-webCLI contributors`, `Source: lib/${t.entry} in blog.webcli.app`];
  if (t.name === 'live') notices.push('Includes moment.js, MIT (c) JS Foundation and other contributors, momentjs.com');
  if (t.name === 'math') notices.push((await fs.readFile(path.join(root, 'vendor/temml/LICENSE'), 'utf8')).trim());
  return build({
    entryPoints: [path.join(root, 'lib', t.entry)],
    bundle: true,
    write: false,
    format: 'esm',
    target: 'es2020',
    minify: true,
    legalComments: 'none',
    plugins: [withoutSelf, ...(t.name === 'live' ? [{
      name: 'lazy-math',
      setup(b) {
        b.onResolve({ filter: /\/math-renderer\.js$/ }, () => ({ path: path.join(root, 'lib/math-lazy.js') }));
      },
    }] : [])],
    banner: { js: `/* blog-webcli ${VERSION} ${t.what}. ${notices.join('. ')}. */` },
    metafile: true,
  });
}

export async function buildTarget(t) {
  const result = await bundle(t);
  const code = result.outputFiles[0].text;
  return `// Generated by cli/build-live.js from lib/${t.entry}. Do not edit.\nexport const ${t.constant} = ${JSON.stringify(code)};\n`;
}

// Every source file a script is built from, relative to the repository: what ends up inside other people's pages.
export async function bundleInputs(t) {
  const result = await bundle(t);
  return Object.keys(result.metafile.inputs).filter((f) => !f.includes('stub:')).sort();
}

// vendor/moment/moment.esm.js: the vendored moment.js (a UMD script, MIT) given a module of its own, so the generator, the
// live renderer and the reader all import one formatter and print the same text. Its own file is untouched.
export async function momentModule() {
  const src = await fs.readFile(path.join(root, 'vendor', 'moment', 'moment.min.js'), 'utf8');
  return `// Generated by cli/build-live.js from vendor/moment/moment.min.js (moment.js, MIT). Do not edit.\nconst module = { exports: {} };\nconst exports = module.exports;\n// moment looks for a locale file by name, inside a try; there are none here and it stays English\nconst require = () => { throw new Error('no locales'); };\n${src.trimEnd()}\nexport default module.exports;\n`;
}

export async function animateModule() {
  const dir = path.join(root, 'vendor', 'animate');
  // The host document is already UTF-8; a charset rule cannot be embedded inside another stylesheet.
  const css = (await fs.readFile(path.join(dir, 'animate.min.css'), 'utf8')).replace(/^@charset "UTF-8";/, '');
  const licence = await fs.readFile(path.join(dir, 'LICENSE'), 'utf8');
  const names = [...new Set([...css.matchAll(/@keyframes\s+([\w-]+)/g)].map((m) => m[1]))];
  if (!names.includes('fadeIn')) throw new Error('Animate.css has no fadeIn keyframes.');
  return `// Generated by cli/build-live.js from vendor/animate/animate.min.css (Animate.css, MIT). Do not edit.\nexport const ANIMATE_CSS = ${JSON.stringify(`/*\n${licence.trim()}\n*/\n${css.trim()}`)};\nexport const ANIMATION_NAMES = ${JSON.stringify(names)};\n`;
}

// Keep upstream intact. Exclude DOM-only methods and exports by AST range, then let
// esbuild remove their unused helpers. The shared renderer must remain DOM-free.
export async function temmlModule() {
  const src = await fs.readFile(path.join(root, 'vendor/temml/temml.mjs'), 'utf8');
  const ast = parse(src, { ecmaVersion: 'latest', sourceType: 'module' });
  const edits = [];
  let methods = 0, exports = 0, quirks = 0;
  const visit = (node) => {
    if (!node || typeof node !== 'object') return;
    if (node.type === 'IfStatement' && node.test.type === 'BinaryExpression' &&
        node.test.operator === '!==' && node.test.left.type === 'UnaryExpression' &&
        node.test.left.operator === 'typeof' && node.test.left.argument.name === 'document' &&
        node.test.right.value === 'undefined') {
      edits.push({ start: node.start, end: node.end, text: '' });
      quirks++;
      return;
    }
    if (node.type === 'MethodDefinition' && node.key.name === 'toNode') {
      edits.push({ start: node.start, end: node.end, text: '' });
      methods++;
      return;
    }
    if (node.type === 'ExportNamedDeclaration') {
      if (node.specifiers.length !== 1 || node.specifiers[0].exported.name !== 'default') throw new Error('Temml exports changed; review the string-only adapter.');
      edits.push({ start: node.start, end: node.end, text: 'export { renderToString, ParseError };' });
      exports++;
      return;
    }
    for (const value of Object.values(node)) {
      if (Array.isArray(value)) value.forEach(visit);
      else if (value && typeof value === 'object') visit(value);
    }
  };
  visit(ast);
  if (methods !== 7 || exports !== 1 || quirks !== 1) throw new Error('Temml DOM surface changed; review the string-only adapter.');
  let text = src;
  for (const edit of edits.sort((a, b) => b.start - a.start)) text = text.slice(0, edit.start) + edit.text + text.slice(edit.end);
  const licence = await fs.readFile(path.join(root, 'vendor/temml/LICENSE'), 'utf8');
  const result = await build({
    stdin: { contents: text, sourcefile: 'temml.mjs', resolveDir: path.join(root, 'vendor/temml') },
    bundle: true, write: false, platform: 'neutral', format: 'esm', target: 'es2020',
    minify: true, legalComments: 'none',
    banner: { js: `// Generated by cli/build-live.js from unmodified temml.mjs; string-only API, DOM methods excluded.\n/*\n${licence.trim()}\n*/` },
  });
  return result.outputFiles[0].text;
}

// app-build.json: which build of the editor this is. The id is a digest of every script the editor runs (app/ and lib/). A tab that
// was opened before an update keeps running the old scripts, and what it generates is then not what the current version would write:
// the editor compares this file with the one it started with before it sends anything (see ensureCurrent in app/app.js).
export async function appBuild() {
  const files = [];
  for (const dir of ['app', 'lib']) for (const f of (await fs.readdir(path.join(root, dir))).sort()) if (f.endsWith('.js')) files.push(`${dir}/${f}`);
  const h = createHash('sha256');
  for (const f of files) h.update(`${f}\n${await fs.readFile(path.join(root, f), 'utf8')}\n`);
  return `${JSON.stringify({ id: h.digest('hex').slice(0, 16), version: VERSION })}\n`;
}

// Kept for the existing drift test.
export const buildLive = () => buildTarget(TARGETS[0]);

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = false;
  // first: the live renderer bundles it
  const moment = await momentModule();
  const mfile = path.join(root, 'vendor', 'moment', 'moment.esm.js');
  if (check) {
    const have = await fs.readFile(mfile, 'utf8').catch(() => '');
    if (have !== moment) {
      console.error('vendor/moment/moment.esm.js is stale: run `node cli/build-live.js`');
      stale = true;
    } else console.log('ok: vendor/moment/moment.esm.js matches vendor/moment/moment.min.js');
  } else {
    await fs.writeFile(mfile, moment);
    console.log(`wrote vendor/moment/moment.esm.js (${moment.length} bytes)`);
  }
  const animate = await animateModule();
  const afile = path.join(root, 'vendor', 'animate', 'animate.esm.js');
  if (check) {
    const have = await fs.readFile(afile, 'utf8').catch(() => '');
    if (have !== animate) {
      console.error('vendor/animate/animate.esm.js is stale: run `node cli/build-live.js`');
      stale = true;
    } else console.log('ok: vendor/animate/animate.esm.js matches Animate.css and its licence');
  } else {
    await fs.writeFile(afile, animate);
    console.log(`wrote vendor/animate/animate.esm.js (${animate.length} bytes)`);
  }
  const temml = await temmlModule();
  const tfile = path.join(root, 'vendor/temml/temml.esm.js');
  if (check) {
    const have = await fs.readFile(tfile, 'utf8').catch(() => '');
    if (have !== temml) {
      console.error('vendor/temml/temml.esm.js is stale: run `node cli/build-live.js`');
      stale = true;
    } else console.log('ok: vendor/temml/temml.esm.js matches Temml and its licence');
  } else {
    await fs.writeFile(tfile, temml);
    console.log(`wrote vendor/temml/temml.esm.js (${temml.length} bytes)`);
  }
  for (const t of TARGETS) {
    const text = await buildTarget(t);
    const file = path.join(root, 'lib', t.out);
    if (check) {
      const have = await fs.readFile(file, 'utf8').catch(() => '');
      if (have !== text) {
        console.error(`lib/${t.out} is stale: run \`node cli/build-live.js\``);
        stale = true;
      } else console.log(`ok: lib/${t.out} matches its sources`);
    } else {
      await fs.writeFile(file, text);
      console.log(`wrote lib/${t.out} (${text.length} bytes)`);
    }
  }
  const build = await appBuild();
  const bfile = path.join(root, 'app-build.json');
  if (check) {
    const have = await fs.readFile(bfile, 'utf8').catch(() => '');
    if (have !== build) {
      console.error('app-build.json is stale: run `node cli/build-live.js`');
      stale = true;
    } else console.log('ok: app-build.json matches app/ and lib/');
  } else {
    await fs.writeFile(bfile, build);
    console.log(`wrote app-build.json (${build.trim()})`);
  }
  if (stale) process.exit(1);
}
