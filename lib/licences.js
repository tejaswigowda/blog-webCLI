// Every licence a blog depends on, in one place: recorded in blog.json, written to
// licences.json, stamped into each generated page as a comment, and shown in the app.
import { GENERATOR } from './page.js';

// the runtime's licence (lib/LICENSE): what the generator writes into a page's comment and licences.json
const GENERATOR_LICENCE = 'MIT';

const clean = (o) => Object.fromEntries(Object.entries(o).filter(([, v]) => v !== undefined && v !== null && v !== ''));

// The files of a theme that are under a licence of their own (a photograph in a GPL theme), as [{ path, licence }]; undefined when there are none.
const assetLicences = (m) => (m && m.asset_licences && Object.keys(m.asset_licences).length ? Object.entries(m.asset_licences).sort(([a], [b]) => (a < b ? -1 : 1)).map(([path, licence]) => ({ path, licence })) : undefined);

// loaded: { theme?, extensions? } — the verified packs, when available, add source and attribution.
export function licenceRecords(blog, loaded = {}) {
  const out = [];
  if (blog.theme && typeof blog.theme === 'object') {
    const m = loaded.theme && loaded.theme.manifest;
    out.push(clean({ kind: 'theme', name: blog.theme.name, version: blog.theme.version, licence: blog.theme.licence, repo: blog.theme.repo, ref: blog.theme.ref, sha256: blog.theme.sha256, contract: m && m.class_contract, source: m && m.source, attribution: m && m.attribution, dropped: m && m.dropped, assets: assetLicences(m) }));
  } else {
    out.push({ kind: 'theme', name: 'default', licence: GENERATOR_LICENCE, builtin: true });
  }
  (blog.extensions || []).forEach((pin, i) => {
    const m = loaded.extensions && loaded.extensions[i] && loaded.extensions[i].manifest;
    out.push(clean({ kind: 'extension', name: pin.name, version: pin.version, licence: pin.licence, repo: pin.repo, ref: pin.ref, sha256: pin.sha256, extensionKind: m && m.kind, hooks: m && m.hooks, source: m && m.source, attribution: m && m.attribution }));
  });
  return out;
}

export function licencesJson(blog, loaded) {
  return JSON.stringify({ version: 1, generator: { name: GENERATOR, licence: GENERATOR_LICENCE }, blog: { title: blog.title, author: blog.author }, dependencies: licenceRecords(blog, loaded) }, null, 2) + '\n';
}

// An HTML comment; "--" is not allowed inside one.
const safe = (s) => String(s).replace(/--+/g, '-').replace(/>/g, '');

export function licenceComment(blog, loaded) {
  const lines = licenceRecords(blog, loaded).map((r) => `  ${r.kind}: ${safe(r.name)}${r.version ? ` ${safe(r.version)}` : ''} — ${safe(r.licence)}${r.repo ? ` — ${safe(r.repo)}@${safe(r.ref)}` : ' — built in'}${r.source ? ` — ${safe(r.source)}` : ''}${r.attribution ? ` — ${safe(r.attribution)}` : ''}${r.assets ? ` — plus ${r.assets.map((a) => `${safe(a.licence)} for ${safe(a.path)}`).join(', ')}` : ''}`);
  return `<!--\nGenerated by ${GENERATOR} (${GENERATOR_LICENCE}). Licences this page depends on:\n${lines.join('\n')}\n-->`;
}
